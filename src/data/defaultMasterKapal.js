export function mergeWithDefaultMasterKapal(existingList = []) {
  if (!Array.isArray(existingList) || existingList.length === 0) {
    return DEFAULT_MASTER_KAPAL;
  }

  const existingMapByAgenda = new Map();
  const existingMapByName = new Map();

  existingList.forEach((item) => {
    if (item.noAgenda) {
      existingMapByAgenda.set(item.noAgenda.trim().toUpperCase(), item);
    }
    if (item.namaKapal) {
      existingMapByName.set(item.namaKapal.trim().toUpperCase(), item);
    }
  });

  const merged = existingList.map((item) => {
    const defaultByAgenda = item.noAgenda ? DEFAULT_MASTER_KAPAL.find(d => d.noAgenda.toUpperCase() === item.noAgenda.trim().toUpperCase()) : null;
    const defaultByName = item.namaKapal ? DEFAULT_MASTER_KAPAL.find(d => d.namaKapal.toUpperCase() === item.namaKapal.trim().toUpperCase()) : null;
    const def = defaultByAgenda || defaultByName;

    if (def) {
      return {
        ...def,
        ...item,
        pemohon: item.pemohon || def.pemohon || '',
        jenisSurvey: item.jenisSurvey || def.jenisSurvey || ''
      };
    }
    return item;
  });

  // Add any defaults that are not in existing list
  DEFAULT_MASTER_KAPAL.forEach((def) => {
    const exists = (def.noAgenda && existingMapByAgenda.has(def.noAgenda.toUpperCase())) ||
                   (def.namaKapal && existingMapByName.has(def.namaKapal.toUpperCase()));
    if (!exists) {
      merged.push(def);
    }
  });

  return merged;
}
